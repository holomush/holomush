package charname_test

import (
	"os"
	"path/filepath"
	"regexp"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/holomush/holomush/internal/charname"
)

const (
	generatedTablePath = "confusables_table_gen.go"
	generatorPath      = "../../cmd/internal/gen-confusables/main.go"
)

var (
	generatedVersionRe = regexp.MustCompile(`const UnicodeVersion = "([^"]+)"`)
	pinnedVersionRe    = regexp.MustCompile(`pinnedUnicodeVersion = "([^"]+)"`)
	pinnedDigestRe     = regexp.MustCompile(`confusablesSHA256 = "([0-9a-f]{64})"`)
)

func readMatch(t *testing.T, path string, re *regexp.Regexp) string {
	t.Helper()
	body, err := os.ReadFile(filepath.Clean(path))
	require.NoError(t, err, "reading %s", path)

	m := re.FindSubmatch(body)
	require.Len(t, m, 2, "%s does not match %s", path, re)
	return string(m[1])
}

// This is the D-23 meta-test. The generated table and the generator's pin are
// two files, and a hand edit or a half-finished version bump can leave them
// disagreeing — at which point every character row would record a Unicode
// version the skeleton beside it was not computed from.
//
// It reads both files textually rather than importing the generator, because
// the generator is package main and its pin is unexported.
func TestThePinnedUnicodeVersionAndTheGeneratedConstantAgree(t *testing.T) {
	generated := readMatch(t, generatedTablePath, generatedVersionRe)
	pinned := readMatch(t, generatorPath, pinnedVersionRe)

	assert.Equal(t, pinned, generated,
		"the generator pins Unicode %s but the committed table declares %s — run `task generate:confusables` and commit the result",
		pinned, generated)
}

func TestTheExportedUnicodeVersionIsTheOneTheCommittedTableDeclares(t *testing.T) {
	// Guards the compiled constant against the file, so a stale build cache or
	// a second UnicodeVersion declaration cannot hide a mismatch.
	assert.Equal(t, readMatch(t, generatedTablePath, generatedVersionRe), charname.UnicodeVersion)
}

func TestTheGeneratorPinsAnInputDigestAlongsideItsUnicodeVersion(t *testing.T) {
	// Version-addressing prevents an accidental upgrade; only the digest
	// prevents an upstream replacement of the bytes at that URL. A generator
	// that lost its digest constant would still emit a plausible table.
	assert.Len(t, readMatch(t, generatorPath, pinnedDigestRe), 64)
}

func TestTheGeneratedTableCarriesTheDoNotEditMarker(t *testing.T) {
	body, err := os.ReadFile(filepath.Clean(generatedTablePath))
	require.NoError(t, err)
	assert.Contains(t, string(body), "// Code generated by gen-confusables. DO NOT EDIT.")
}
