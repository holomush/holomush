// minimalConfusables is a byte-for-byte-shaped miniature of the real
// confusables.txt: the same header comment carrying the `# Version:` field,
// then two `source ; target ; MA # comment` mapping lines.
const minimalConfusables = `# confusables.txt
#
# Unicode Security Mechanisms for UTS #39
# Version: 17.0.0
#
0430 ;	0061 ;	MA	# ( а → a ) CYRILLIC SMALL LETTER A → LATIN SMALL LETTER A	#
0440 ;	0070 ;	MA	# ( р → p ) CYRILLIC SMALL LETTER ER → LATIN SMALL LETTER P	#
`

func writeTempInput(t *testing.T, body string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "confusables.txt")
	require.NoError(t, os.WriteFile(path, []byte(body), 0o600))
	return path
}

func TestGenerateRejectsInputWhoseDigestDoesNotMatchThePinnedConstant(t *testing.T) {
	// One byte changed relative to the digest the test pins below: the check
	// must fire before any code is emitted, and must name BOTH digests so an
	// operator can tell a deliberate refresh from a substituted file.
	input := writeTempInput(t, minimalConfusables+"# tampered\n")
	out := filepath.Join(t.TempDir(), "confusables_table_gen.go")

	err := generate(config{
		inputPath:      input,
		outputPath:     out,
		expectedSHA256: sha256Hex([]byte(minimalConfusables)),
		wantVersion:    "17.0.0",
	})

	require.Error(t, err)
	assert.Contains(t, err.Error(), sha256Hex([]byte(minimalConfusables)), "error names the expected digest")
	assert.Contains(t, err.Error(), sha256Hex([]byte(minimalConfusables+"# tampered\n")), "error names the observed digest")
	assert.NoFileExists(t, out, "no code is emitted when the digest check fails")
}

func TestGenerateEmitsTheVersionConstantAndMappingTableForAMatchingInput(t *testing.T) {
	input := writeTempInput(t, minimalConfusables)
	out := filepath.Join(t.TempDir(), "confusables_table_gen.go")

	require.NoError(t, generate(config{
		inputPath:      input,
		outputPath:     out,
		expectedSHA256: sha256Hex([]byte(minimalConfusables)),
		wantVersion:    "17.0.0",
	}))

	body, err := os.ReadFile(out)
	require.NoError(t, err)
	got := string(body)

	assert.Contains(t, got, "// Code generated by gen-confusables. DO NOT EDIT.")
	assert.Contains(t, got, `const UnicodeVersion = "17.0.0"`)
	assert.Contains(t, got, "0x0430:")
	assert.Contains(t, got, "0x0440:")
	assert.True(t, strings.HasPrefix(got, "// SPDX-License-Identifier: Apache-2.0"), "generated file carries the SPDX header")
}

func TestGenerateRejectsAnInputWhoseVersionHeaderDisagreesWithThePinnedVersion(t *testing.T) {
	skewed := strings.Replace(minimalConfusables, "# Version: 17.0.0", "# Version: 16.0.0", 1)
	input := writeTempInput(t, skewed)
	out := filepath.Join(t.TempDir(), "confusables_table_gen.go")

	err := generate(config{
		inputPath:      input,
		outputPath:     out,
		expectedSHA256: sha256Hex([]byte(skewed)),
		wantVersion:    "17.0.0",
	})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "16.0.0")
	assert.Contains(t, err.Error(), "17.0.0")
	assert.NoFileExists(t, out)
}

func TestParseConfusablesReadsSourceRuneAndMultiRuneTargetSequence(t *testing.T) {
	version, table, err := parseConfusables([]byte(minimalConfusables + "1D4D0 ;	0041 0301 ;	MA	# comment\n"))
	require.NoError(t, err)

	assert.Equal(t, "17.0.0", version)
	assert.Equal(t, "a", table[0x0430])
	assert.Equal(t, "p", table[0x0440])
	assert.Equal(t, "Á", table[0x1D4D0], "a multi-codepoint target is preserved as a rune sequence")
}
